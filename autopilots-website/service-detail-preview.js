const updateServiceRoi = () => {
  const root = document.querySelector("[data-service-roi]");
  if (!root) return;
  const get = (name) => Number(root.querySelector(`[data-roi-input="${name}"]`)?.value || 0);
  const volume = get("volume");
  const minutes = get("minutes");
  const rate = get("rate");
  const margin = get("margin");
  const processed = Math.round(volume * (rate / 100));
  const hours = (processed * minutes) / 60;
  const timeValue = hours * 55;
  const extraClients = Math.max(1, Math.round(processed * 0.045));
  const extraMargin = extraClients * margin;
  const values = { volume, minutes, rate: `${rate}%`, margin: euro.format(margin) };
  Object.entries(values).forEach(([name, value]) => {
    const el = root.querySelector(`[data-roi-value="${name}"]`);
    if (el) el.textContent = value;
  });
  const results = {
    processed: number.format(processed),
    hours: number.format(hours),
    timeValue: euro.format(timeValue),
    extraClients: number.format(extraClients),
    extraMargin: euro.format(extraMargin)
  };
  Object.entries(results).forEach(([name, value]) => {
    const el = root.querySelector(`[data-roi-result="${name}"]`);
    if (el) el.textContent = value;
  });
};

document.querySelectorAll("[data-roi-input]").forEach((input) => {
  input.addEventListener("input", updateServiceRoi);
});
updateServiceRoi();

